UPDATE classes SET grade_level = BTRIM(grade_level)
WHERE grade_level IS DISTINCT FROM BTRIM(grade_level);

INSERT INTO grades (name, sort_order)
SELECT existing.grade_level,
  (100 + ROW_NUMBER() OVER (ORDER BY LOWER(existing.grade_level), existing.grade_level))::SMALLINT
FROM (
  SELECT DISTINCT grade_level
  FROM classes
  WHERE BTRIM(grade_level) <> ''
) existing
ON CONFLICT DO NOTHING;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'fk_classes_grade'
      AND conrelid = 'public.classes'::regclass
  ) THEN
    ALTER TABLE classes ADD CONSTRAINT fk_classes_grade
      FOREIGN KEY (grade_level) REFERENCES grades(name);
  END IF;
END;
$$;

COMMIT;

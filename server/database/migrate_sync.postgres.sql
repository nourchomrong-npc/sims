  singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
  node_id UUID NOT NULL DEFAULT gen_random_uuid(),
  mode VARCHAR(20) NOT NULL DEFAULT 'disabled'
    CHECK (mode IN ('disabled', 'local_only', 'cloud_only', 'hybrid')),
  auto_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  auto_configured BOOLEAN NOT NULL DEFAULT FALSE,
  initial_snapshot_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
ALTER TABLE sync_state ADD COLUMN IF NOT EXISTS initial_snapshot_at TIMESTAMPTZ;
ALTER TABLE sync_state ADD COLUMN IF NOT EXISTS auto_enabled BOOLEAN NOT NULL DEFAULT TRUE;
ALTER TABLE sync_state ADD COLUMN IF NOT EXISTS auto_configured BOOLEAN NOT NULL DEFAULT FALSE;

INSERT INTO sync_state (singleton) VALUES (TRUE)
ON CONFLICT (singleton) DO NOTHING;

ALTER TABLE class_schedule_time_slots
  ADD COLUMN IF NOT EXISTS class_public_id UUID;
UPDATE class_schedule_time_slots time_slot
SET class_public_id = class_record.public_id
FROM classes class_record
WHERE time_slot.class_id = class_record.id
  AND time_slot.class_public_id IS DISTINCT FROM class_record.public_id;
ALTER TABLE class_schedule_time_slots
  ALTER COLUMN class_public_id SET NOT NULL;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'fk_schedule_time_slot_class_public'
      AND conrelid = 'public.class_schedule_time_slots'::regclass
  ) THEN
    ALTER TABLE class_schedule_time_slots
      ADD CONSTRAINT fk_schedule_time_slot_class_public
      FOREIGN KEY (class_public_id) REFERENCES classes(public_id) ON DELETE CASCADE;
  END IF;
END;
$$;

CREATE OR REPLACE FUNCTION set_class_schedule_public_id()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  SELECT class_record.public_id INTO NEW.class_public_id
  FROM classes class_record
  WHERE class_record.id = NEW.class_id;
  IF NEW.class_public_id IS NULL THEN
    RAISE EXCEPTION 'Class % does not exist', NEW.class_id USING ERRCODE = '23503';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS class_schedule_time_slots_set_public_id ON class_schedule_time_slots;
CREATE TRIGGER class_schedule_time_slots_set_public_id
  BEFORE INSERT OR UPDATE OF class_id ON class_schedule_time_slots
  FOR EACH ROW EXECUTE FUNCTION set_class_schedule_public_id();

CREATE TABLE IF NOT EXISTS sync_outbox (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id UUID NOT NULL DEFAULT gen_random_uuid() UNIQUE,
  origin_node_id UUID NOT NULL,
  table_name VARCHAR(80) NOT NULL,
  operation VARCHAR(10) NOT NULL CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE')),
  record_key JSONB NOT NULL,
  before_data JSONB,
  after_data JSONB,
  status VARCHAR(16) NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'synced', 'failed', 'conflict')),
  attempts INTEGER NOT NULL DEFAULT 0 CHECK (attempts >= 0),

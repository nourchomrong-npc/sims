CREATE OR REPLACE FUNCTION sync_row_as_json(row_data JSONB, source_table TEXT)
RETURNS JSONB
LANGUAGE SQL
STABLE
AS $$
  SELECT COALESCE(jsonb_object_agg(
    field.key,
    CASE
      WHEN column_info.data_type = 'bigint' AND jsonb_typeof(field.value) = 'number'
        THEN to_jsonb(field.value #>> '{}')
      ELSE field.value
    END
  ), '{}'::JSONB)
  FROM jsonb_each(row_data) field
  LEFT JOIN information_schema.columns column_info
    ON column_info.table_schema = 'public'
    AND column_info.table_name = source_table
    AND column_info.column_name = field.key
$$;

CREATE OR REPLACE FUNCTION sync_record_key(source_table TEXT, row_data JSONB)
RETURNS JSONB
LANGUAGE plpgsql
IMMUTABLE
AS $$
BEGIN
  IF source_table = 'class_schedule_time_slots' THEN
    RETURN jsonb_build_object('class_public_id', row_data -> 'class_public_id', 'start_time', row_data -> 'start_time');
  ELSIF source_table = 'trash_records' THEN
    RETURN jsonb_build_object('entity_type', row_data -> 'entity_type', 'record_public_id', row_data -> 'record_public_id');
  ELSIF row_data ? 'public_id' THEN
    RETURN jsonb_build_object('public_id', row_data -> 'public_id');
  END IF;
  RETURN jsonb_build_object('id', row_data -> 'id');
END;
$$;

CREATE OR REPLACE FUNCTION capture_sync_change()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
  row_data JSONB;
  prior_data JSONB;
  change_key JSONB;
  node_id UUID;
BEGIN
  IF current_setting('app.sync_apply', TRUE) = 'true' THEN
    IF TG_OP = 'DELETE' THEN
      RETURN OLD;
    END IF;
    RETURN NEW;
  END IF;

  IF TG_OP = 'DELETE' THEN
    row_data := sync_row_as_json(to_jsonb(OLD), TG_TABLE_NAME);
    prior_data := row_data;
  ELSE
    row_data := sync_row_as_json(to_jsonb(NEW), TG_TABLE_NAME);
    IF TG_OP = 'UPDATE' THEN
      prior_data := sync_row_as_json(to_jsonb(OLD), TG_TABLE_NAME);
    END IF;
  END IF;

  change_key := sync_record_key(TG_TABLE_NAME, row_data);

  SELECT state.node_id INTO node_id FROM sync_state state WHERE state.singleton = TRUE;
  INSERT INTO sync_outbox (
    origin_node_id, table_name, operation, record_key, before_data, after_data
  ) VALUES (
    node_id, TG_TABLE_NAME, TG_OP, change_key,
    CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE prior_data END,
    CASE WHEN TG_OP = 'DELETE' THEN NULL ELSE row_data END
  );

  IF TG_OP = 'DELETE' THEN
    RETURN OLD;
  END IF;
  RETURN NEW;
END;
$$;

DO $$
DECLARE
  tracked_table TEXT;
  tracked_tables TEXT[] := ARRAY[
    'users', 'trash_records', 'academic_years', 'teachers', 'classes', 'students',
    'student_photos', 'terms', 'student_enrollments', 'subjects', 'teacher_assignments',
    'class_schedules', 'class_schedule_time_slots', 'attendance_records', 'assessments',
    'student_scores', 'grading_scales', 'activity_logs'
  ];
BEGIN
  FOREACH tracked_table IN ARRAY tracked_tables LOOP
    IF to_regclass(format('public.%I', tracked_table)) IS NOT NULL THEN
      EXECUTE format('DROP TRIGGER IF EXISTS %I ON public.%I', tracked_table || '_sync_change', tracked_table);
      EXECUTE format(
        'CREATE TRIGGER %I AFTER INSERT OR UPDATE OR DELETE ON public.%I FOR EACH ROW EXECUTE FUNCTION capture_sync_change()',
        tracked_table || '_sync_change',
        tracked_table
      );
    END IF;
  END LOOP;
END;
$$;

DO $$
DECLARE
  snapshot_table TEXT;
  snapshot_tables TEXT[] := ARRAY[
    'academic_years', 'teachers', 'users', 'classes', 'students', 'terms',
    'subjects', 'student_enrollments', 'teacher_assignments', 'class_schedules',
    'class_schedule_time_slots', 'attendance_records', 'assessments', 'student_scores',
    'grading_scales', 'student_photos', 'trash_records', 'activity_logs'
  ];
BEGIN
  IF (SELECT initial_snapshot_at FROM sync_state WHERE singleton = TRUE) IS NULL THEN
    FOREACH snapshot_table IN ARRAY snapshot_tables LOOP
      IF to_regclass(format('public.%I', snapshot_table)) IS NOT NULL THEN
        EXECUTE format(
          'INSERT INTO sync_outbox (origin_node_id, table_name, operation, record_key, after_data)
           SELECT state.node_id, %L, ''INSERT'', sync_record_key(%L, to_jsonb(record)),
             sync_row_as_json(to_jsonb(record), %L)
           FROM public.%I record CROSS JOIN sync_state state
           WHERE state.singleton = TRUE',
          snapshot_table, snapshot_table, snapshot_table, snapshot_table
        );
      END IF;
    END LOOP;
    UPDATE sync_state SET initial_snapshot_at = CURRENT_TIMESTAMP WHERE singleton = TRUE;
  END IF;
END;
$$;


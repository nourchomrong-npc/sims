CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id UUID NOT NULL DEFAULT gen_random_uuid(),
  username VARCHAR(80) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  full_name VARCHAR(150) NOT NULL,
  role VARCHAR(30) NOT NULL CHECK (role IN ('Administrator', 'Teacher', 'School Manager')),
  teacher_id BIGINT NULL,
  must_change_password SMALLINT NOT NULL DEFAULT 0,
  active SMALLINT NOT NULL DEFAULT 1,
  is_deleted SMALLINT NOT NULL DEFAULT 0,
  deleted_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_users_public_id UNIQUE (public_id),
  CONSTRAINT uq_users_username UNIQUE (username),
  CONSTRAINT uq_users_teacher_id UNIQUE (teacher_id)
);
CREATE INDEX IF NOT EXISTS idx_users_role_active ON users (role, active);
CREATE INDEX IF NOT EXISTS idx_users_name ON users (full_name);
CREATE INDEX IF NOT EXISTS idx_users_username_trgm ON users USING GIN (username gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_users_full_name_trgm ON users USING GIN (full_name gin_trgm_ops);

CREATE TABLE IF NOT EXISTS user_sessions (
  sid VARCHAR NOT NULL PRIMARY KEY,
  sess JSON NOT NULL,
  expire TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_user_sessions_expire ON user_sessions (expire);

CREATE TABLE IF NOT EXISTS trash_records (
  entity_type VARCHAR(40) NOT NULL,
  record_public_id UUID NOT NULL,
  deleted_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  deleted_by BIGINT,
  PRIMARY KEY (entity_type, record_public_id)
);
CREATE INDEX IF NOT EXISTS idx_trash_records_deleted_at
  ON trash_records (deleted_at DESC);

CREATE TABLE IF NOT EXISTS academic_years (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id UUID NOT NULL DEFAULT gen_random_uuid(),
  name VARCHAR(30) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  is_current SMALLINT NOT NULL DEFAULT 0,
  status VARCHAR(16) NOT NULL DEFAULT 'Upcoming'
    CHECK (status IN ('Upcoming', 'Current', 'Closed')),
  CONSTRAINT uq_academic_years_public_id UNIQUE (public_id),
  CONSTRAINT uq_academic_year_name UNIQUE (name),
  CHECK ((status = 'Current') = (is_current = 1)),
  CHECK (end_date > start_date)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_academic_year_current
  ON academic_years (is_current) WHERE is_current = 1;

CREATE TABLE IF NOT EXISTS teachers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id UUID NOT NULL DEFAULT gen_random_uuid(),
  teacher_code VARCHAR(30) NOT NULL,
  full_name VARCHAR(150) NOT NULL,
  email VARCHAR(254),
  phone VARCHAR(30),
  hire_date DATE,
  employment_status VARCHAR(20) NOT NULL DEFAULT 'Active'
    CHECK (employment_status IN ('Active', 'On Leave', 'Inactive')),
  is_deleted SMALLINT NOT NULL DEFAULT 0,
  deleted_at TIMESTAMP,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_teachers_public_id UNIQUE (public_id),
  CONSTRAINT uq_teachers_code UNIQUE (teacher_code),
  CONSTRAINT uq_teachers_email UNIQUE (email)
);
CREATE INDEX IF NOT EXISTS idx_teachers_status ON teachers (employment_status);
CREATE INDEX IF NOT EXISTS idx_teachers_name ON teachers (full_name);
CREATE INDEX IF NOT EXISTS idx_teachers_code_trgm ON teachers USING GIN (teacher_code gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_teachers_full_name_trgm ON teachers USING GIN (full_name gin_trgm_ops);
ALTER TABLE users DROP CONSTRAINT IF EXISTS fk_users_teacher;
ALTER TABLE users ADD CONSTRAINT fk_users_teacher
  FOREIGN KEY (teacher_id) REFERENCES teachers(id) ON DELETE SET NULL;

CREATE TABLE IF NOT EXISTS grades (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id UUID NOT NULL DEFAULT gen_random_uuid(),
  name VARCHAR(50) NOT NULL,
  sort_order SMALLINT NOT NULL,
  active SMALLINT NOT NULL DEFAULT 1,
  is_deleted SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_grades_public_id UNIQUE (public_id),
  CONSTRAINT uq_grades_name UNIQUE (name),
  CONSTRAINT uq_grades_sort_order UNIQUE (sort_order),
  CHECK (active IN (0, 1)),
  CHECK (is_deleted IN (0, 1))
);

CREATE TABLE IF NOT EXISTS classes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id UUID NOT NULL DEFAULT gen_random_uuid(),
  name VARCHAR(80) NOT NULL,
  grade_level VARCHAR(50) NOT NULL,
  academic_year_id BIGINT NOT NULL,
  capacity SMALLINT NOT NULL DEFAULT 40,
  homeroom_teacher_id BIGINT,
  active SMALLINT NOT NULL DEFAULT 1,
  is_deleted SMALLINT NOT NULL DEFAULT 0,
  deleted_at TIMESTAMP,
  CONSTRAINT uq_classes_public_id UNIQUE (public_id),
  CONSTRAINT uq_classes_year_name UNIQUE (academic_year_id, name),
  CONSTRAINT fk_classes_year FOREIGN KEY (academic_year_id) REFERENCES academic_years(id),
  CONSTRAINT fk_classes_homeroom FOREIGN KEY (homeroom_teacher_id) REFERENCES teachers(id) ON DELETE SET NULL,
  CONSTRAINT fk_classes_grade FOREIGN KEY (grade_level) REFERENCES grades(name)
);
CREATE INDEX IF NOT EXISTS idx_classes_grade ON classes (grade_level);
CREATE INDEX IF NOT EXISTS idx_classes_grade_name ON classes (grade_level, name);
CREATE INDEX IF NOT EXISTS idx_classes_name_trgm ON classes USING GIN (name gin_trgm_ops);

CREATE TABLE IF NOT EXISTS students (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id UUID NOT NULL DEFAULT gen_random_uuid(),
  student_code VARCHAR(30) NOT NULL,
  english_name VARCHAR(150) NOT NULL,
  khmer_name VARCHAR(150),
  gender VARCHAR(10) NOT NULL CHECK (gender IN ('Female', 'Male', 'Other')),
  date_of_birth DATE,
  place_of_birth VARCHAR(255),
  address VARCHAR(500),
  phone VARCHAR(30),
  email VARCHAR(254),
  guardian_name VARCHAR(150),
  guardian_phone VARCHAR(30),
  enrollment_date DATE NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'Active'
    CHECK (status IN ('Active', 'Archived', 'Graduated', 'Withdrawn')),
  is_deleted SMALLINT NOT NULL DEFAULT 0,
  deleted_at TIMESTAMP,
  photo_url VARCHAR(2048),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_students_public_id UNIQUE (public_id),
  CONSTRAINT uq_students_code UNIQUE (student_code)
);
CREATE INDEX IF NOT EXISTS idx_students_name ON students (english_name);
CREATE INDEX IF NOT EXISTS idx_students_status ON students (status);
CREATE INDEX IF NOT EXISTS idx_students_enrollment ON students (enrollment_date);
CREATE INDEX IF NOT EXISTS idx_students_code_trgm ON students USING GIN (student_code gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_students_english_name_trgm ON students USING GIN (english_name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS idx_students_khmer_name_trgm ON students USING GIN (khmer_name gin_trgm_ops);

CREATE TABLE IF NOT EXISTS terms (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id UUID NOT NULL DEFAULT gen_random_uuid(),
  academic_year_id BIGINT NOT NULL,
  name VARCHAR(80) NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  CONSTRAINT uq_terms_public_id UNIQUE (public_id),
  CONSTRAINT uq_terms_year_name UNIQUE (academic_year_id, name),
  CONSTRAINT fk_terms_year FOREIGN KEY (academic_year_id) REFERENCES academic_years(id),
  CHECK (end_date >= start_date)
);

CREATE TABLE IF NOT EXISTS student_enrollments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id UUID NOT NULL DEFAULT gen_random_uuid(),
  student_id BIGINT NOT NULL,
  class_id BIGINT NOT NULL,
  academic_year_id BIGINT NOT NULL,
  enrollment_date DATE NOT NULL,
  exit_date DATE,
  current SMALLINT NOT NULL DEFAULT 1,
  enrollment_type VARCHAR(16) NOT NULL DEFAULT 'Homeroom'
    CHECK (enrollment_type IN ('Homeroom', 'Subject')),
  subject_id BIGINT,
  promotion_status VARCHAR(24)
    CHECK (promotion_status IS NULL OR promotion_status IN
      ('Promoted', 'Conditional Promotion', 'Retained/Repeat', 'Graduated', 'Transferred', 'Pending')),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_student_enrollments_public_id UNIQUE (public_id),
  CONSTRAINT fk_enrollment_student FOREIGN KEY (student_id) REFERENCES students(id),
  CONSTRAINT fk_enrollment_class FOREIGN KEY (class_id) REFERENCES classes(id),
  CONSTRAINT fk_enrollment_year FOREIGN KEY (academic_year_id) REFERENCES academic_years(id),
  CHECK ((enrollment_type = 'Homeroom' AND subject_id IS NULL) OR
    (enrollment_type = 'Subject' AND subject_id IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS idx_student_enrollment_date ON student_enrollments (enrollment_date);
CREATE INDEX IF NOT EXISTS idx_enrollment_class_current ON student_enrollments (class_id, current);
CREATE INDEX IF NOT EXISTS idx_enrollment_student_current ON student_enrollments (student_id, current);
CREATE UNIQUE INDEX IF NOT EXISTS uq_student_enrollment_assignment
  ON student_enrollments (student_id, class_id, academic_year_id, COALESCE(subject_id, 0));
CREATE UNIQUE INDEX IF NOT EXISTS uq_student_homeroom_per_year
  ON student_enrollments (student_id, academic_year_id)
  WHERE enrollment_type = 'Homeroom' AND current = 1;

CREATE TABLE IF NOT EXISTS academic_year_transitions (

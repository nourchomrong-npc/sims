BEGIN;

ALTER TABLE academic_years
  ADD COLUMN IF NOT EXISTS status VARCHAR(16) NOT NULL DEFAULT 'Upcoming';

WITH ranked_years AS (
  SELECT id, is_current,
    ROW_NUMBER() OVER (ORDER BY (is_current = 1) DESC, start_date DESC, id DESC) AS position
  FROM academic_years
)
UPDATE academic_years year
SET is_current = CASE WHEN ranked.position = 1 AND ranked.is_current = 1 THEN 1 ELSE 0 END,
    status = CASE
      WHEN ranked.position = 1 AND ranked.is_current = 1 THEN 'Current'
      WHEN year.end_date < CURRENT_DATE THEN 'Closed'
      ELSE 'Upcoming'
    END
FROM ranked_years ranked
WHERE year.id = ranked.id;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'academic_years_status_check'
      AND conrelid = 'public.academic_years'::regclass
  ) THEN
    ALTER TABLE academic_years ADD CONSTRAINT academic_years_status_check
      CHECK (status IN ('Upcoming', 'Current', 'Closed'));
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'academic_years_current_consistency_check'
      AND conrelid = 'public.academic_years'::regclass
  ) THEN
    ALTER TABLE academic_years ADD CONSTRAINT academic_years_current_consistency_check
      CHECK ((status = 'Current') = (is_current = 1));
  END IF;
END;
$$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_academic_year_current
  ON academic_years (is_current) WHERE is_current = 1;

ALTER TABLE student_enrollments
  ADD COLUMN IF NOT EXISTS enrollment_type VARCHAR(16) NOT NULL DEFAULT 'Homeroom',
  ADD COLUMN IF NOT EXISTS subject_id BIGINT,
  ADD COLUMN IF NOT EXISTS promotion_status VARCHAR(24);

ALTER TABLE student_enrollments DROP CONSTRAINT IF EXISTS uq_student_class_year;
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'student_enrollments_enrollment_type_check'
      AND conrelid = 'public.student_enrollments'::regclass
  ) THEN
    ALTER TABLE student_enrollments ADD CONSTRAINT student_enrollments_enrollment_type_check
      CHECK (enrollment_type IN ('Homeroom', 'Subject'));
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'student_enrollments_promotion_status_check'
      AND conrelid = 'public.student_enrollments'::regclass
  ) THEN
    ALTER TABLE student_enrollments ADD CONSTRAINT student_enrollments_promotion_status_check
      CHECK (promotion_status IS NULL OR promotion_status IN
        ('Promoted', 'Conditional Promotion', 'Retained/Repeat', 'Graduated', 'Transferred', 'Pending'));
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'student_enrollments_type_subject_check'
      AND conrelid = 'public.student_enrollments'::regclass
  ) THEN
    ALTER TABLE student_enrollments ADD CONSTRAINT student_enrollments_type_subject_check
      CHECK ((enrollment_type = 'Homeroom' AND subject_id IS NULL) OR
        (enrollment_type = 'Subject' AND subject_id IS NOT NULL));
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'fk_enrollment_subject'
      AND conrelid = 'public.student_enrollments'::regclass
  ) THEN
    ALTER TABLE student_enrollments ADD CONSTRAINT fk_enrollment_subject
      FOREIGN KEY (subject_id) REFERENCES subjects(id);
  END IF;
END;
$$;

CREATE UNIQUE INDEX IF NOT EXISTS uq_student_enrollment_assignment
  ON student_enrollments (student_id, class_id, academic_year_id, COALESCE(subject_id, 0));
CREATE UNIQUE INDEX IF NOT EXISTS uq_student_homeroom_per_year
  ON student_enrollments (student_id, academic_year_id)
  WHERE enrollment_type = 'Homeroom' AND current = 1;
CREATE INDEX IF NOT EXISTS idx_student_enrollment_subject
  ON student_enrollments (subject_id, academic_year_id, current);

CREATE TABLE IF NOT EXISTS academic_year_transitions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id UUID NOT NULL DEFAULT gen_random_uuid(),
  source_year_id BIGINT REFERENCES academic_years(id),
  target_year_id BIGINT NOT NULL UNIQUE REFERENCES academic_years(id),
  created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  completed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  details JSONB NOT NULL DEFAULT '{}'::jsonb,
  CONSTRAINT uq_academic_year_transitions_public_id UNIQUE (public_id)
);

CREATE TABLE IF NOT EXISTS academic_year_transition_students (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id UUID NOT NULL DEFAULT gen_random_uuid(),
  transition_id BIGINT NOT NULL REFERENCES academic_year_transitions(id) ON DELETE CASCADE,
  student_id BIGINT NOT NULL REFERENCES students(id),
  source_enrollment_id BIGINT REFERENCES student_enrollments(id) ON DELETE SET NULL,
  new_enrollment_id BIGINT REFERENCES student_enrollments(id) ON DELETE SET NULL,
  promotion_status VARCHAR(24) NOT NULL
    CHECK (promotion_status IN ('Promoted', 'Conditional Promotion', 'Retained/Repeat', 'Graduated', 'Transferred', 'Pending')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_academic_year_transition_students_public_id UNIQUE (public_id),
  CONSTRAINT uq_transition_student UNIQUE (transition_id, student_id)
);
CREATE INDEX IF NOT EXISTS idx_transition_students_student ON academic_year_transition_students (student_id);

CREATE TABLE IF NOT EXISTS student_subject_outcomes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id UUID NOT NULL DEFAULT gen_random_uuid(),
  transition_id BIGINT NOT NULL REFERENCES academic_year_transitions(id) ON DELETE CASCADE,
  student_enrollment_id BIGINT NOT NULL REFERENCES student_enrollments(id) ON DELETE CASCADE,
  outcome VARCHAR(16) NOT NULL
    CHECK (outcome IN ('Pass', 'Fail', 'Incomplete', 'Not Assessed')),
  recorded_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_student_subject_outcomes_public_id UNIQUE (public_id),
  CONSTRAINT uq_transition_subject_outcome UNIQUE (transition_id, student_enrollment_id)
);
CREATE INDEX IF NOT EXISTS idx_subject_outcomes_enrollment ON student_subject_outcomes (student_enrollment_id);

ALTER TABLE attendance_records
  ADD COLUMN IF NOT EXISTS student_enrollment_id BIGINT REFERENCES student_enrollments(id) ON DELETE SET NULL;
ALTER TABLE student_scores
  ADD COLUMN IF NOT EXISTS student_enrollment_id BIGINT REFERENCES student_enrollments(id) ON DELETE SET NULL;
CREATE INDEX IF NOT EXISTS idx_attendance_student_enrollment ON attendance_records (student_enrollment_id);
CREATE INDEX IF NOT EXISTS idx_scores_student_enrollment ON student_scores (student_enrollment_id);

COMMIT;
